"""
Extended medicine reference data - batch 4.

WHY THIS BATCH EXISTS
---------------------
Batches 1-3 covered the classes a Western formulary leads with. They are thin on
what actually moves across an Indian community pharmacy counter: the fixed-dose
combinations Indian GPs prescribe, the antitubercular and antimalarial regimen
drugs the national programmes supply, the anthelmintics for school deworming
rounds, the ORS and zinc pair for childhood diarrhoea, and the topical and
ophthalmic preparations that make up a large share of unit sales.

WHAT THIS DELIBERATELY DOES NOT DO
----------------------------------
It does not fabricate. Every molecular formula, half-life and dose ceiling below
is the published value. Where a figure is not reliably published for a
combination product the field is left as None rather than guessed - an invented
half-life reads exactly like a real one and would be carried straight into a
clinical decision.

A plausible but invented interaction is worse than a missing row. A pharmacist
who sees a drug is absent will look it up; one who sees a fabricated interaction
will believe it. The count therefore matters far less than the accuracy of each
line, and the set grows by verified tier rather than by padding. For the full
national range, import_medicines.py loads a real CDSCO, Jan Aushadhi or NPPA
catalogue.
"""

