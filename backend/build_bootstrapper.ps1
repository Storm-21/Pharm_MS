# PharmMS Setup - the small web bootstrapper.
#
#   .\build_bootstrapper.ps1                          full build
#   .\build_bootstrapper.ps1 -SkipAppBuild            reuse dist\PharmMS.exe
#   .\build_bootstrapper.ps1 -Version 2.2.0           stamp a version
#
# Produces:  dist\PharmMS-Setup.exe   (a few hundred KB, NOT 15 MB)
#
# WHY THIS REPLACES THE EMBEDDED-PAYLOAD INSTALLER
# ------------------------------------------------
# The previous installer embedded the whole ~15 MB application as a base64 blob
# inside a PowerShell script and compiled that into the .exe. It worked and
# needed no internet, but it had two costs that turned out to matter more:
#
#   1. Every release carried a 15 MB download for a 15 MB app, and GitHub
#      Releases stored a third copy. Twelve releases is 180 MB of storage just
#      to deliver the same payload.
#   2. The version the user installed could NOT be changed after the fact. Once
#      the .exe was built, that was the bytes you got - there was no way to
#      re-pull a rebuilt payload, and a corrupted download meant starting over.
#
# So this is a bootstrapper: a tiny .exe that carries no application code at all,
# only the knowledge of WHERE to get it. It downloads the payload from the
# GitHub Release at install time, verifies its SHA-256 against a value baked
# into this file, and only then installs. The result:
#
#   * the download is ~200 KB instead of ~15 MB
#   * the payload is fetched over HTTPS from GitHub, and a tampered or truncated
#     download fails the hash check and is refused rather than installed
#   * progress is real - it reports megabytes received, not a fake bar
#   * the same small .exe can install any released version (`-Tag v2.3.0`)
#
# TRADE-OFF, STATED PLAINLY
# -------------------------
# This installer REQUIRES an internet connection, and it depends on GitHub being
# reachable. The embedded-payload installer did not. That is a deliberate
# exchange: a 200 KB download that needs the network, instead of a 15 MB
# download that does not. build_installer.ps1 is kept for anyone who needs the
# offline variant; both produce a file with the same name, so run one or the
# other, not both.

[CmdletBinding()]
param(
    [switch]$SkipAppBuild,
    [string]$Version = '2.2.0',
    [string]$Repository = 'Storm-21/Pharm_MS',
    [string]$Tag = 'latest'
)

$ErrorActionPreference = 'Stop'
# See the note in build_exe.ps1: GitHub Actions runs `shell: pwsh` (PowerShell 7),
# where a native command writing to stderr raises a terminating
# NativeCommandError under 'Stop'. npm and pip both write progress there, so a
# perfectly good build could abort on a deprecation notice.
$PSNativeCommandUseErrorActionPreference = $false

$BackendDir = $PSScriptRoot
$PayloadExe = Join-Path $BackendDir 'dist\PharmMS.exe'
$BuildStage = Join-Path $BackendDir 'build\bootstrapper'
$SetupPs1   = Join-Path $BuildStage 'bootstrap.ps1'
$StubCs     = Join-Path $BuildStage 'stub.cs'
$OutSetup   = Join-Path $BackendDir 'dist\PharmMS-Setup.exe'

function Write-Step($m) { Write-Host "==> $m" -ForegroundColor Cyan }
function Fail($m) { Write-Host "ERROR: $m" -ForegroundColor Red; exit 1 }

# --- 1. Build the application payload ---------------------------------------
# The payload is built here but NOT embedded. It is uploaded to the Release
# separately, and this installer downloads it. Building it now is what lets the
# script compute the expected SHA-256 and bake that in - so the bootstrapper
# refuses a payload that does not match the one it was built against.
if (-not $SkipAppBuild) {
    Write-Step 'Building the application payload'
    & (Join-Path $BackendDir 'build_exe.ps1')
    if (-not (Test-Path $PayloadExe)) {
        Fail "Application build did not produce $PayloadExe"
    }
}

if (-not (Test-Path $PayloadExe)) {
    Fail "Payload not found: $PayloadExe. Run build_exe.ps1 first."
}

$payloadBytes = [IO.File]::ReadAllBytes($PayloadExe)
$payloadHash = (Get-FileHash $PayloadExe -Algorithm SHA256).Hash
$payloadMb = [math]::Round($payloadBytes.Length / 1MB, 1)
$payloadName = 'PharmMS.exe'

Write-Host "    payload: $payloadMb MB, sha256 $($payloadHash.Substring(0, 16))..."

# The download URL is pinned to the release ASSET path, which is what the
# landing page links to. 'latest' resolves to the newest release, so a user who
# downloads the bootstrapper once still gets the current build.
if ($Tag -eq 'latest') {
    $downloadUrl = "https://github.com/$Repository/releases/latest/download/$payloadName"
} else {
    $downloadUrl = "https://github.com/$Repository/releases/download/$Tag/$payloadName"
}

# --- 2. Assemble the bootstrap script ---------------------------------------
Write-Step 'Assembling the bootstrap script'
New-Item -ItemType Directory -Path $BuildStage -Force | Out-Null

$template = @'
# PharmMS Setup - web bootstrapper.
# Generated by build_bootstrapper.ps1. Do not edit by hand.
#
# This file carries NO application code. It knows only where to fetch the
# payload and what hash to expect. See build_bootstrapper.ps1 for why.

