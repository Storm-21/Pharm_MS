$AppName     = 'Pharmacy Management System'
$ShortName   = 'PharmMS'
$Version     = '__VERSION__'
$Publisher   = 'Jayant'
$PayloadHash = '__HASH__'
$PayloadName = '__PAYLOAD_NAME__'
$DownloadUrl = '__URL__'
$Repository  = '__REPO__'
$Tag         = '__TAG__'

$InstallDir  = Join-Path $env:LOCALAPPDATA 'Programs\PharmMS'
$DataDir     = Join-Path $env:LOCALAPPDATA 'PharmMS'
$StartMenu   = Join-Path $env:APPDATA 'Microsoft\Windows\Start Menu\Programs'
$DesktopDir  = [Environment]::GetFolderPath('Desktop')
$ExeName     = "$ShortName.exe"

Add-Type -AssemblyName System.Windows.Forms
Add-Type -AssemblyName System.Drawing

# ---------------------------------------------------------------- UI helpers --
function New-Dialog($text, $title, $buttons) {
    $form = New-Object Windows.Forms.Form
    $form.Text = $title
    $form.Size = New-Object Drawing.Size(560, 290)
    $form.StartPosition = 'CenterScreen'
    $form.FormBorderStyle = 'FixedDialog'
    $form.MaximizeBox = $false
    $form.MinimizeBox = $false
    $form.BackColor = [Drawing.Color]::White
    $form.Font = New-Object Drawing.Font('Segoe UI', 9)

    $label = New-Object Windows.Forms.Label
    $label.Text = $text
    $label.Location = New-Object Drawing.Point(22, 20)
    $label.Size = New-Object Drawing.Size(505, 175)
    $form.Controls.Add($label)

    $x = 510 - (($buttons.Count) * 108)
    foreach ($b in $buttons) {
        $btn = New-Object Windows.Forms.Button
        $btn.Text = $b.Text
        $btn.Size = New-Object Drawing.Size(100, 30)
        $btn.Location = New-Object Drawing.Point($x, 205)
        $btn.FlatStyle = 'System'
        $btn.Add_Click({ param($s, $e) $script:dialogResult = $s.Tag; $form.Close() })
        $btn.Tag = $b.Value
        $form.Controls.Add($btn)
        $x += 108
    }
    $form.AcceptButton = $form.Controls |
        Where-Object { $_ -is [Windows.Forms.Button] } | Select-Object -First 1
    $script:dialogResult = [Windows.Forms.DialogResult]::Cancel
    $form.ShowDialog() | Out-Null
    return $script:dialogResult
}

