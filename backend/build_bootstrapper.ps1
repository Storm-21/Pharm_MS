# ---------------------------------------------------------------- installing --
$ui = $null
if (-not $Silent) { $ui = Show-ProgressForm }
$tempFile = Join-Path ([IO.Path]::GetTempPath()) "PharmMS-$([Guid]::NewGuid().ToString('N')).exe"

try {
    # --- Download -----------------------------------------------------------
    Update-Progress $ui "Downloading $AppName..." 0.02 "From $DownloadUrl"

    $downloaded = $false
    $attempts = 3
    $lastError = $null
    for ($i = 1; $i -le $attempts -and -not $downloaded; $i++) {
        try {
            if ($i -gt 1) {
                Update-Progress $ui "Retrying download (attempt $i of $attempts)..." -1
                Start-Sleep -Seconds 2
            }

            # WebClient gives progress callbacks, which HttpClient does not
            # surface as simply from PowerShell. The download is one file over
            # HTTPS, so it is a good fit.
            $client = New-Object Net.WebClient
            $client.Headers.Add('User-Agent', "PharmMS-Bootstrapper/$Version")

            $received = 0
            $client.add_DownloadProgressChanged({
                param($sender, $e)
                if ($e.TotalBytesToReceive -gt 0) {
                    $fraction = 0.05 + 0.65 * ($e.BytesReceived / $e.TotalBytesToReceive)
                    $gotMb = [math]::Round($e.BytesReceived / 1MB, 1)
                    $totMb = [math]::Round($e.TotalBytesToReceive / 1MB, 1)
                    Update-Progress $ui 'Downloading...' $fraction "$gotMb MB of $totMb MB"
                }
            })

            $client.DownloadFile($DownloadUrl, $tempFile)
            $client.Dispose()
            $downloaded = $true
        } catch {
            $lastError = $_.Exception.Message
        }
    }

    if (-not $downloaded) {
        if ($ui) { $ui.Form.Close() }
        # A failed install must not leave a shortcut pointing at a program that
        # is not there. The old installer had no cleanup path at all, and a
        # machine was found with a desktop shortcut whose target did not exist -
        # the user clicks it and Windows reports a missing file, with nothing
        # explaining that the install never completed.
        Remove-StaleShortcuts
        $message = @"
Could not download $AppName.

The installer needs an internet connection for this step.

  $lastError

You can download the file manually from:
  https://github.com/$Repository/releases

and run it directly - it is the same program this installer
would have downloaded.
"@
        if ($Silent) { Write-Host $message; exit 1 }
        [Windows.Forms.MessageBox]::Show($message, "$AppName Setup", 'OK', 'Error') | Out-Null
        exit 1
    }

    # --- Verify -------------------------------------------------------------
    # TLS proves the transport, not the payload. Hashing the file against the
    # value compiled into this installer proves it is the build this
    # bootstrapper was made for, so a substituted or truncated download is
    # refused instead of installed.
    Update-Progress $ui 'Verifying the download...' 0.72

    $actual = (Get-FileHash $tempFile -Algorithm SHA256).Hash
    if ($actual -ne $PayloadHash) {
        Remove-Item $tempFile -Force -ErrorAction SilentlyContinue
        if ($ui) { $ui.Form.Close() }
        Remove-StaleShortcuts
        $message = @"
The downloaded file failed its integrity check and was NOT installed.

  expected: $($PayloadHash.Substring(0,24))...
  received: $($actual.Substring(0,24))...

This usually means the download was incomplete or was modified
in transit. Nothing has been changed on your computer.

Please try again, or download the file manually from:
  https://github.com/$Repository/releases
"@
        if ($Silent) { Write-Host $message; exit 1 }
        [Windows.Forms.MessageBox]::Show($message, "$AppName Setup", 'OK', 'Error') | Out-Null
        exit 1
    }

    Update-Progress $ui 'Download verified.' 0.78

    # --- Install ------------------------------------------------------------
    Get-Process $ShortName -ErrorAction SilentlyContinue | ForEach-Object {
        Update-Progress $ui 'Closing a running copy...' -1
        $_.CloseMainWindow() | Out-Null
        Start-Sleep -Milliseconds 700
        if (-not $_.HasExited) { $_.Kill() }
    }

    Update-Progress $ui "Creating $InstallDir..." 0.82
    New-Item -ItemType Directory -Path $InstallDir -Force | Out-Null

    Update-Progress $ui 'Writing application files...' 0.88
    $target = Join-Path $InstallDir $ExeName
    Copy-Item $tempFile $target -Force
    Remove-Item $tempFile -Force -ErrorAction SilentlyContinue
    Update-Progress $ui 'Application files written.' 0.92

    # Shortcuts
    Update-Progress $ui 'Creating shortcuts...' 0.94
    $shell = New-Object -ComObject WScript.Shell
    foreach ($lnkPath in @(
        (Join-Path $DesktopDir "$ShortName.lnk"),
        (Join-Path $StartMenu "$ShortName.lnk")
    )) {
        $lnk = $shell.CreateShortcut($lnkPath)
        $lnk.TargetPath = $target
        $lnk.WorkingDirectory = $InstallDir
        $lnk.IconLocation = $target
        $lnk.Description = $AppName
        $lnk.Save()
    }
    Update-Progress $ui 'Shortcuts created.' 0.96

    # Uninstaller + Add/Remove Programs entry
    Update-Progress $ui 'Registering the uninstaller...' 0.98
    $uninstallerPath = Join-Path $InstallDir 'Uninstall-PharmMS.ps1'
    $uninstaller = @"
`$ErrorActionPreference = 'SilentlyContinue'
`$ShortName = '$ShortName'
`$InstallDir = '$InstallDir'
`$DataDir = '$DataDir'
Get-Process `$ShortName | ForEach-Object { `$_.CloseMainWindow() | Out-Null; Start-Sleep -Milliseconds 700; if (-not `$_.HasExited) { `$_.Kill() } }
Remove-Item (Join-Path ([Environment]::GetFolderPath('Desktop')) "`$ShortName.lnk") -Force
Remove-Item (Join-Path `$env:APPDATA 'Microsoft\Windows\Start Menu\Programs' "`$ShortName.lnk") -Force
Remove-Item 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\PharmMS' -Force -ErrorAction SilentlyContinue
Remove-Item 'HKCU:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\PharmMS' -Force -ErrorAction SilentlyContinue
Remove-Item `$InstallDir -Recurse -Force
Add-Type -AssemblyName System.Windows.Forms
`$answer = [Windows.Forms.MessageBox]::Show(
    "PharmMS has been removed.`n`nAlso delete all patient records in:`n`$DataDir ?`n`nThis cannot be undone.",
    'PharmMS Uninstall', 'YesNo', 'Warning')
if (`$answer -eq 'Yes') {
    Remove-Item `$DataDir -Recurse -Force
} else {
    [Windows.Forms.MessageBox]::Show("Your records were kept at:`n`$DataDir", 'PharmMS Uninstall', 'OK', 'Information') | Out-Null
}
"@
    Set-Content -Path $uninstallerPath -Value $uninstaller -Encoding UTF8

    $uninstallCmd = "powershell.exe -NoProfile -ExecutionPolicy Bypass -File `"$uninstallerPath`""
    $key = 'HKCU:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\PharmMS'
    New-Item -Path $key -Force | Out-Null
    Set-ItemProperty -Path $key -Name 'DisplayName'     -Value $AppName
    Set-ItemProperty -Path $key -Name 'DisplayVersion'  -Value $Version
    Set-ItemProperty -Path $key -Name 'Publisher'       -Value $Publisher
    Set-ItemProperty -Path $key -Name 'DisplayIcon'     -Value $target
    Set-ItemProperty -Path $key -Name 'InstallLocation' -Value $InstallDir
    Set-ItemProperty -Path $key -Name 'UninstallString' -Value $uninstallCmd
    Set-ItemProperty -Path $key -Name 'NoModify'        -Value 1 -Type DWord
    Set-ItemProperty -Path $key -Name 'NoRepair'        -Value 1 -Type DWord
    try {
        $size = [math]::Round((Get-Item $target).Length / 1024)
        Set-ItemProperty -Path $key -Name 'EstimatedSize' -Value $size -Type DWord
    } catch { }

    Update-Progress $ui 'Finishing...' 1.0
}
finally {
    if (Test-Path $tempFile) { Remove-Item $tempFile -Force -ErrorAction SilentlyContinue }
    if ($ui) {
        $ui.Form.Close()
        $ui.Form.Dispose()
    }
}

