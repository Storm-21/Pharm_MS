# The icon is a source asset, but a build should not die because one optional
# decoration is missing - csc.exe rejects a bad or absent path outright with
# "CS1583: not a valid Win32 resource file", which is a confusing way to be told
# the icon is simply not there. Warn and build without it instead.
$iconArgs = @()
if (Test-Path $iconPath) {
    # The switch and its value must be ONE command-line token: csc.exe expects
    # "/win32icon:path" and treats a separated path as an extra, unconsumed
    # argument (CS2005). Joining them into a single array element is the form
    # that works on both PowerShell 5.1 and 7.
    $iconArgs = @("/win32icon:$iconPath")
} else {
    Write-Host "    WARNING: $iconPath not found - building without a custom icon." -ForegroundColor Yellow
}

Push-Location $BuildStage
try {
    & $csc /nologo /target:winexe `
        "/out:$OutSetup" `
        "/resource:$SetupPs1,bootstrap.ps1" `
        @iconArgs `
        /reference:System.dll `
        /reference:System.Windows.Forms.dll `
        "$StubCs"
    if ($LASTEXITCODE -ne 0) { Fail 'csc.exe failed to compile the bootstrapper.' }
}
finally {
    Pop-Location
}

if (-not (Test-Path $OutSetup)) { Fail "Installer was not produced at $OutSetup" }

# --- 4. Report ---------------------------------------------------------------
$setupKb = [math]::Round((Get-Item $OutSetup).Length / 1KB, 1)

Write-Host ''
Write-Host '==============================================================' -ForegroundColor Green
Write-Host '  Bootstrapper built' -ForegroundColor Green
Write-Host '==============================================================' -ForegroundColor Green
Write-Host "  Setup file : $OutSetup"
Write-Host "  Size       : $setupKb KB  (payload is downloaded, not embedded)"
Write-Host "  Downloads  : $downloadUrl"
Write-Host "  Expects    : sha256 $($payloadHash.Substring(0, 16))..."
Write-Host ''
Write-Host '  Upload BOTH files to the same GitHub Release:' -ForegroundColor Yellow
Write-Host "    1. $OutSetup        <- the small download users click"
Write-Host "    2. $PayloadExe      <- $payloadMb MB payload, renamed to $payloadName"
Write-Host ''
Write-Host '  The setup file is useless without the payload in the same' -ForegroundColor Yellow
Write-Host '  release, and will refuse a payload whose hash differs.' -ForegroundColor Yellow
Write-Host '==============================================================' -ForegroundColor Green