Write-Step 'Compiling the bootstrapper executable'

# A tiny C# stub that runs the embedded PowerShell script. Compiled with the
# C# compiler that ships with the .NET Framework, so no extra tooling is needed.
$stub = @'
using System;
using System.Diagnostics;
using System.IO;
using System.Reflection;
using System.Text;

class PharmMSSetup
{
    [STAThread]
    static int Main(string[] args)
    {
        try
        {
            string temp = Path.Combine(Path.GetTempPath(), "PharmMS-Setup-" + Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(temp);
            string script = Path.Combine(temp, "bootstrap.ps1");

            // The bootstrap script is embedded beside the stub as a resource.
            Assembly self = Assembly.GetExecutingAssembly();
            string[] names = self.GetManifestResourceNames();
            string resource = null;
            foreach (string n in names)
            {
                if (n.EndsWith("bootstrap.ps1", StringComparison.OrdinalIgnoreCase)) { resource = n; break; }
            }
            if (resource == null)
            {
                Console.Error.WriteLine("Internal error: bootstrap payload missing.");
                return 2;
            }

            using (Stream s = self.GetManifestResourceStream(resource))
            using (StreamReader r = new StreamReader(s, Encoding.UTF8))
            {
                File.WriteAllText(script, r.ReadToEnd(), new UTF8Encoding(false));
            }

            // Resolve PowerShell by ABSOLUTE PATH. A bare "powershell.exe" is
            // not reliable: it is absent from PATH on some machines, which makes
            // the installer exit silently with no window and no error message.
            string ps = Path.Combine(
                Environment.GetFolderPath(Environment.SpecialFolder.System),
                @"WindowsPowerShell\v1.0\powershell.exe");
            if (!File.Exists(ps))
            {
                ps = "powershell.exe";
            }

            // Forward command-line arguments (notably -Silent) to the script.
            // Without this the wizard always appears and an automated install
            // hangs waiting for a click that never comes.
            StringBuilder forwarded = new StringBuilder();
            foreach (string a in args)
            {
                if (forwarded.Length > 0) { forwarded.Append(' '); }
                forwarded.Append('"').Append(a.Replace("\"", "\\\"")).Append('"');
            }

            ProcessStartInfo psi = new ProcessStartInfo();
            psi.FileName = ps;
            psi.UseShellExecute = false;
            psi.Arguments = "-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File \"" + script + "\" " + forwarded.ToString();

            Process p = Process.Start(psi);
            p.WaitForExit();

            // Clean up the temp folder. This MUST NOT fail silently.
            //
            // The previous version called Directory.Delete inside an empty
            // catch, so if the delete failed the folder was simply left behind
            // with no indication at all. A machine was found carrying four
            // orphaned PharmMS-Setup-* folders, one per run, each with the
            // bootstrap script still inside - unbounded growth in %TEMP% from
            // an installer that had already exited successfully.
            //
            // Two things can hold the folder: the PowerShell child may not have
            // fully released its file handles when WaitForExit returns, and
            // antivirus may still be scanning the script it just executed. So
            // retry briefly, and if it genuinely cannot be removed, say so on
            // stderr rather than pretending the cleanup succeeded.
            bool cleaned = false;
            for (int attempt = 0; attempt < 5 && !cleaned; attempt++)
            {
                try
                {
                    if (Directory.Exists(temp))
                    {
                        Directory.Delete(temp, true);
                    }
                    cleaned = true;
                }
                catch (IOException)
                {
                    System.Threading.Thread.Sleep(200);
                }
                catch (UnauthorizedAccessException)
                {
                    System.Threading.Thread.Sleep(200);
                }
            }
            if (!cleaned)
            {
                Console.Error.WriteLine("Note: could not remove the temporary folder " + temp);
            }

            return p.ExitCode;
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine(ex.Message);
            return 1;
        }
    }
}
'@

