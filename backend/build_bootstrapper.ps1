function Update-Progress($ui, $message, $fraction, $detail) {
    if (-not $ui) { return }
    # $fraction = -1 means "no measurable progress" - update the labels only.
    # A ProgressBar rejects any Value below Minimum, so the comparison has to
    # guard the assignment itself rather than sit inside it.
    $ui.Label.Text = $message
    if ($PSBoundParameters.ContainsKey('detail') -and $null -ne $detail) {
        $ui.Detail.Text = $detail
    }
    if ($fraction -ge 0) {
        $clamped = [Math]::Max(0, [Math]::Min(1000, [int]($fraction * 1000)))
        $ui.Bar.Value = $clamped
    }
    $ui.Form.Refresh()
    [Windows.Forms.Application]::DoEvents()
}

# Removes shortcuts that point at a program which is not installed.
#
# WHY: an earlier installer left a desktop shortcut behind after a failed or
# partial install. The shortcut survives, its target does not, and the user is
# left clicking an icon that Windows answers with "the item was not found".
# Clearing only the BROKEN ones means a valid existing install is never
# disturbed by a later attempt that happens to fail.
function Remove-StaleShortcuts {
    $target = Join-Path $InstallDir $ExeName
    if (Test-Path $target) { return }   # a real install exists; leave it alone

    foreach ($lnkPath in @(
        (Join-Path $DesktopDir "$ShortName.lnk"),
        (Join-Path $StartMenu "$ShortName.lnk")
    )) {
        if (Test-Path $lnkPath) {
            Remove-Item $lnkPath -Force -ErrorAction SilentlyContinue
        }
    }
    # The uninstall entry is equally meaningless without the program.
    Remove-Item 'HKCU:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\PharmMS' `
        -Recurse -Force -ErrorAction SilentlyContinue
}

# ------------------------------------------------------- headless detection --
# A GUI cannot always be shown: silent/automated installs run with -Silent, and
# some execution contexts have no interactive desktop at all. In those cases the
# install still completes and the wizard is skipped, rather than the installer
# opening nothing and appearing to do nothing.
$Silent = $false
if ($args -contains '-Silent' -or $env:PHARMS_SILENT -eq '1') { $Silent = $true }

function Test-CanShowGui {
    try {
        $null = [Windows.Forms.SystemInformation]::UserInteractive
        $probe = New-Object Windows.Forms.Form
        $probe.Dispose()
        return $true
    } catch {
        return $false
    }
}

if (-not $Silent -and -not (Test-CanShowGui)) {
    Write-Host 'No interactive desktop available - running silently.'
    $Silent = $true
}

# --------------------------------------------------------------- TLS setup ---
# Force TLS 1.2. On Windows PowerShell 5.1 the default is still SSL3/TLS1.0 on
# some builds, and GitHub refuses those outright - the download fails with a
# connection error that looks like the network is down rather than a protocol
# mismatch.
try {
    [Net.ServicePointManager]::SecurityProtocol =
        [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12
} catch {
    # Not fatal - PowerShell 6+ defaults to TLS 1.2 and the type may not exist.
}

